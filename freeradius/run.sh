#!/usr/bin/env bash
# FreeRADIUS add-on - container entrypoint.
#
# Renders the FreeRADIUS configuration from the Home Assistant add-on options
# (/data/options.json) and starts the RADIUS server in the foreground.
#
# Persistent data (survives restarts and rebuilds) lives in /data:
#   /data/certs  EAP certificate authority and server certificate
# Everything else is regenerated from the add-on options on every start.

set -euo pipefail

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------
readonly OPTIONS_FILE="/data/options.json"
readonly RADDB="/etc/raddb"
readonly CLIENTS_CONF="${RADDB}/clients.conf"
readonly USERS_FILE="${RADDB}/mods-config/files/authorize"
readonly CERT_DIR="/data/certs"
readonly SHARE_DIR="/share/freeradius"
readonly DEFAULT_SECRET="changeme"
readonly RENEW_BEFORE_SECONDS=2592000 # renew certificates 30 days before expiry

# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
log_info()  { printf '[%s] INFO:  %s\n' "$(date '+%F %T')" "$*"; }
log_warn()  { printf '[%s] WARN:  %s\n' "$(date '+%F %T')" "$*" >&2; }
log_error() { printf '[%s] ERROR: %s\n' "$(date '+%F %T')" "$*" >&2; }
die()       { log_error "$*"; exit 1; }

# Run a command silently; print its output only if it fails.
run_quiet() {
    local output
    if ! output=$("$@" 2>&1); then
        log_error "Command failed: $*"
        printf '%s\n' "$output" >&2
        return 1
    fi
}

# Escape backslashes and double quotes for use inside a double-quoted
# FreeRADIUS string.
escape_value() {
    printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'
}

# FreeRADIUS expands %{...} and ${...} inside quoted strings and a line break
# would break the file format, so such values are rejected.
is_unsafe() {
    [[ "$1" == *'%{'* || "$1" == *'${'* || "$1" == *$'\n'* ]]
}

# ---------------------------------------------------------------------------
# Options
# ---------------------------------------------------------------------------
read_options() {
    [[ -f "$OPTIONS_FILE" ]] || die "Options file ${OPTIONS_FILE} not found."

    SHARED_SECRET=$(jq -r '.shared_secret // empty' "$OPTIONS_FILE")
    CLIENT_NETWORK=$(jq -r '.client_network // "0.0.0.0/0"' "$OPTIONS_FILE")
    SERVER_NAME=$(jq -r '.server_name // "freeradius.local"' "$OPTIONS_FILE")
    DEBUG=$(jq -r '.debug // false' "$OPTIONS_FILE")

    [[ -n "$SHARED_SECRET" ]] \
        || die "No shared secret configured. Set 'shared_secret' in the add-on configuration."
    [[ "$SHARED_SECRET" != "$DEFAULT_SECRET" ]] \
        || die "The shared secret still has its default value. Please change it in the add-on configuration."
    if is_unsafe "$SHARED_SECRET"; then
        die 'The shared secret must not contain "%{", "${" or line breaks.'
    fi

    local network_regex='^(\*|[0-9]{1,3}(\.[0-9]{1,3}){3}(/[0-9]{1,2})?)$'
    [[ "$CLIENT_NETWORK" =~ $network_regex ]] \
        || die "Invalid client_network '${CLIENT_NETWORK}'. Use an IPv4 address, a CIDR network or '*'."

    local name_regex='^[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?$'
    [[ "$SERVER_NAME" =~ $name_regex ]] \
        || die "Invalid server_name '${SERVER_NAME}'. Use letters, digits, dots and hyphens only."
}

# ---------------------------------------------------------------------------
# FreeRADIUS configuration
# ---------------------------------------------------------------------------
render_clients() {
    local ipaddr="$CLIENT_NETWORK"
    if [[ "$ipaddr" == "0.0.0.0/0" ]]; then
        ipaddr="*"
    fi
    local secret
    secret=$(escape_value "$SHARED_SECRET")

    log_info "Writing ${CLIENTS_CONF} (allowed clients: ${CLIENT_NETWORK})..."
    cat > "$CLIENTS_CONF" << EOF
# Generated by run.sh - changes are lost on restart.
client lan_clients {
    ipaddr = ${ipaddr}
    secret = "${secret}"
}

client localhost {
    ipaddr = 127.0.0.1
    secret = "${secret}"
}
EOF
}

render_users() {
    local count=0 entry name pass vlan
    local -A seen=()

    log_info "Writing user list to ${USERS_FILE}..."
    printf '# Generated by run.sh - changes are lost on restart.\n\n' > "$USERS_FILE"

    while IFS= read -r entry; do
        name=$(jq -r '.username // empty' <<< "$entry")
        pass=$(jq -r '.password // empty' <<< "$entry")
        vlan=$(jq -r '.vlan // empty' <<< "$entry")

        if [[ -z "$name" || -z "$pass" ]]; then
            log_warn "Skipping a user entry with an empty username or password."
            continue
        fi
        if is_unsafe "$name" || is_unsafe "$pass"; then
            log_warn "Skipping user '${name}': username and password must not contain \"%{\", \"\${\" or line breaks."
            continue
        fi
        if [[ -n "${seen[$name]:-}" ]]; then
            log_warn "Skipping duplicate user '${name}'."
            continue
        fi
        seen[$name]=1

        if [[ -n "$vlan" ]]; then
            cat >> "$USERS_FILE" << EOF
"$(escape_value "$name")" Cleartext-Password := "$(escape_value "$pass")"
        Tunnel-Type = VLAN,
        Tunnel-Medium-Type = IEEE-802,
        Tunnel-Private-Group-Id = "${vlan}"

EOF
            log_info "User '${name}' added (VLAN ${vlan})."
        else
            cat >> "$USERS_FILE" << EOF
"$(escape_value "$name")" Cleartext-Password := "$(escape_value "$pass")"

EOF
            log_info "User '${name}' added (no VLAN)."
        fi
        count=$((count + 1))
    done < <(jq -c '.users[]?' "$OPTIONS_FILE")

    if [[ "$count" -eq 0 ]]; then
        log_warn "No users configured: every login attempt will be rejected."
    else
        log_info "${count} user(s) configured."
    fi
}

# Patch an EAP module configuration file in place:
#  - top-level default_eap_type = peap (offer PEAP to the client)
#  - inside the peap block: default_eap_type = mschapv2 and
#    use_tunneled_reply = yes, so the reply attributes of the inner tunnel
#    (e.g. the VLAN assignment) are copied into the final Access-Accept.
# The patch is idempotent, so it is safe to run on every start.
patch_eap_file() {
    local file="$1" tmp="$1.tmp"
    awk '
        {
            line = $0
            code = line
            sub(/#.*/, "", code)
            if (!in_peap && code ~ /^[[:space:]]*peap[[:space:]]*[{]/) { in_peap = 1; depth = 0 }
            if (in_peap) {
                if (code ~ /^[[:space:]]*default_eap_type[[:space:]]*=/) {
                    sub(/=[[:space:]]*[A-Za-z0-9_]+/, "= mschapv2", line)
                }
                if (code ~ /^[[:space:]]*use_tunneled_reply[[:space:]]*=/) {
                    sub(/=[[:space:]]*[A-Za-z0-9_]+/, "= yes", line)
                }
                depth += gsub(/[{]/, "{", code) - gsub(/[}]/, "}", code)
                if (depth <= 0) in_peap = 0
            } else if (!done && code ~ /^[[:space:]]*default_eap_type[[:space:]]*=/) {
                sub(/=[[:space:]]*[A-Za-z0-9_]+/, "= peap", line)
                done = 1
            }
            print line
        }
    ' "$file" > "$tmp" && cat "$tmp" > "$file"
    rm -f "$tmp"
}

# Configure the EAP module (PEAP + VLAN forwarding) and make sure it is enabled.
configure_eap() {
    local available="${RADDB}/mods-available/eap"
    local enabled="${RADDB}/mods-enabled/eap"
    local file

    [[ -f "$available" ]] || die "EAP module configuration ${available} not found (is freeradius-eap installed?)."

    for file in "$available" "$enabled"; do
        # Only edit regular files; a symlink points to a file that is handled itself.
        if [[ -f "$file" && ! -L "$file" ]]; then
            patch_eap_file "$file"
        fi
    done

    if [[ ! -e "$enabled" ]]; then
        ln -s ../mods-available/eap "$enabled"
    fi
}

# ---------------------------------------------------------------------------
# Certificates (persistent in /data/certs)
# ---------------------------------------------------------------------------
ensure_ca() {
    if [[ -f "${CERT_DIR}/ca.pem" && -f "${CERT_DIR}/ca.key" ]] \
        && openssl x509 -in "${CERT_DIR}/ca.pem" -noout -checkend "$RENEW_BEFORE_SECONDS" > /dev/null 2>&1; then
        return 0
    fi

    log_info "Generating a new certificate authority (valid for 10 years)..."
    run_quiet openssl genrsa -out "${CERT_DIR}/ca.key" 4096
    run_quiet openssl req -x509 -new -nodes -sha256 -days 3650 \
        -key "${CERT_DIR}/ca.key" \
        -subj "/O=Home Assistant/CN=FreeRADIUS CA" \
        -addext "basicConstraints=critical,CA:TRUE" \
        -addext "keyUsage=critical,keyCertSign,cRLSign" \
        -out "${CERT_DIR}/ca.pem"

    # A new CA invalidates every server certificate issued by the old one.
    rm -f "${CERT_DIR}/server.pem" "${CERT_DIR}/server.crt"
}

ensure_server_cert() {
    local name_file="${CERT_DIR}/.server_name"

    if [[ -f "${CERT_DIR}/server.pem" && -f "${CERT_DIR}/server.crt" \
        && "$(cat "$name_file" 2> /dev/null || true)" == "$SERVER_NAME" ]] \
        && openssl x509 -in "${CERT_DIR}/server.crt" -noout -checkend "$RENEW_BEFORE_SECONDS" > /dev/null 2>&1; then
        return 0
    fi

    log_info "Generating a new server certificate for '${SERVER_NAME}' (valid for 5 years)..."
    run_quiet openssl genrsa -out "${CERT_DIR}/server.key" 2048
    run_quiet openssl req -new -sha256 \
        -key "${CERT_DIR}/server.key" \
        -subj "/O=Home Assistant/CN=${SERVER_NAME}" \
        -out "${CERT_DIR}/server.csr"
    cat > "${CERT_DIR}/server.ext" << EOF
basicConstraints=CA:FALSE
keyUsage=digitalSignature,keyEncipherment
extendedKeyUsage=serverAuth
subjectAltName=DNS:${SERVER_NAME}
EOF
    run_quiet openssl x509 -req -sha256 -days 1825 \
        -in "${CERT_DIR}/server.csr" \
        -CA "${CERT_DIR}/ca.pem" -CAkey "${CERT_DIR}/ca.key" -CAcreateserial \
        -extfile "${CERT_DIR}/server.ext" \
        -out "${CERT_DIR}/server.crt"

    # FreeRADIUS reads private key and certificate from the same PEM file.
    cat "${CERT_DIR}/server.key" "${CERT_DIR}/server.crt" > "${CERT_DIR}/server.pem"
    printf '%s' "$SERVER_NAME" > "$name_file"
    rm -f "${CERT_DIR}/server.csr" "${CERT_DIR}/server.ext"
}

ensure_dh() {
    if [[ -f "${CERT_DIR}/dh" ]]; then
        return 0
    fi
    log_info "Generating Diffie-Hellman parameters..."
    run_quiet openssl dhparam -dsaparam -out "${CERT_DIR}/dh" 2048
}

setup_certificates() {
    mkdir -p "$CERT_DIR"
    ensure_ca
    ensure_server_cert
    ensure_dh

    # Point the FreeRADIUS certificate directory to the persistent location.
    rm -rf "${RADDB}/certs"
    ln -s "$CERT_DIR" "${RADDB}/certs"
}

publish_ca() {
    if mkdir -p "$SHARE_DIR" 2> /dev/null && cp "${CERT_DIR}/ca.pem" "${SHARE_DIR}/ca.pem" 2> /dev/null; then
        log_info "CA certificate copied to ${SHARE_DIR}/ca.pem (install it on your clients)."
    else
        log_warn "Could not copy the CA certificate to ${SHARE_DIR}."
    fi
    log_info "CA $(openssl x509 -in "${CERT_DIR}/ca.pem" -noout -fingerprint -sha256)"
}

fix_permissions() {
    if grep -q '^radius:' /etc/group; then
        chown -R root:radius "$CERT_DIR" "$CLIENTS_CONF" "$USERS_FILE"
        chmod 750 "$CERT_DIR"
        find "$CERT_DIR" -type f -exec chmod 640 {} +
        chmod 640 "$CLIENTS_CONF" "$USERS_FILE"
        # The CA key is only needed by this script, never by radiusd.
        chmod 600 "${CERT_DIR}/ca.key"
    else
        log_warn "Group 'radius' not found; leaving file ownership unchanged."
    fi
}

# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
main() {
    log_info "Reading configuration from ${OPTIONS_FILE}..."
    read_options

    render_clients
    render_users
    configure_eap
    setup_certificates
    fix_permissions
    publish_ca

    log_info "Validating FreeRADIUS configuration..."
    if ! radiusd -C -l stdout -d "$RADDB"; then
        die "FreeRADIUS configuration check failed. Enable 'debug' in the add-on configuration for details."
    fi

    if [[ "$DEBUG" == "true" ]]; then
        log_warn "Debug mode is on: the log contains credentials. Disable it after troubleshooting."
        log_info "Starting FreeRADIUS in debug mode..."
        exec radiusd -X -d "$RADDB"
    fi

    log_info "Starting FreeRADIUS..."
    exec radiusd -f -l stdout -d "$RADDB"
}

main "$@"
